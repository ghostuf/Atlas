package python

import (
	"atlas/core"
	"testing"
)

const samplePoetryLock = `# This file is automatically @generated by Poetry and should not be changed by hand.

[[package]]
name = "requests"
version = "2.31.0"
description = "Python HTTP for Humans."
category = "main"
optional = false
python-versions = ">=3.7"

[package.dependencies]
certifi = ">=2017.4.17"
urllib3 = {version = ">=1.21.1,<3", optional = true}

[package.extras]
socks = ["PySocks (>=1.5.6,!=1.5.7)"]

[[package]]
name = "certifi"
version = "2023.7.22"
category = "main"

[[package]]
name = "urllib3"
version = "2.0.4"
category = "main"

[[package]]
name = "pytest"
version = "7.4.0"
groups = ["dev"]

[metadata]
lock-version = "2.0"
python-versions = "^3.11"
content-hash = "deadbeef"

[metadata.files]
requests = [
    {file = "requests-2.31.0-py3-none-any.whl", hash = "sha256:aaaa"},
]
`

const samplePyProjectTOML = `[tool.poetry]
name = "my-python-app"
version = "0.1.0"

[tool.poetry.dependencies]
python = "^3.11"
requests = "^2.31"

[tool.poetry.group.dev.dependencies]
pytest = "^7.4"
`

func TestBuildGraphFromPoetry_EndToEnd(t *testing.T) {
	entries, err := ParsePoetryLock([]byte(samplePoetryLock))
	if err != nil {
		t.Fatalf("ParsePoetryLock: %v", err)
	}
	if len(entries) != 4 {
		t.Fatalf("expected 4 package entries, got %d: %+v", len(entries), entries)
	}

	pd, err := ParsePyProjectTOML([]byte(samplePyProjectTOML))
	if err != nil {
		t.Fatalf("ParsePyProjectTOML: %v", err)
	}
	if pd.Name != "my-python-app" {
		t.Errorf("project name = %q, want my-python-app", pd.Name)
	}
	if len(pd.Main) != 1 || pd.Main[0] != "requests" {
		t.Errorf("Main = %+v, want [requests] (python constraint must be skipped)", pd.Main)
	}
	if len(pd.Dev) != 1 || pd.Dev[0] != "pytest" {
		t.Errorf("Dev = %+v, want [pytest]", pd.Dev)
	}

	g, err := BuildGraphFromPoetry(entries, pd)
	if err != nil {
		t.Fatalf("BuildGraphFromPoetry: %v", err)
	}
	if g.Ecosystem != core.EcosystemPoetry {
		t.Errorf("Ecosystem = %q, want poetry", g.Ecosystem)
	}

	requests := g.Nodes["requests"]
	if requests == nil {
		t.Fatalf("requests node missing")
	}
	if requests.Version != "2.31.0" || requests.Dev {
		t.Errorf("requests = %+v, want version 2.31.0, Dev=false", requests)
	}
	if requests.Depth != 1 || !requests.Direct {
		t.Errorf("requests should be a direct (depth 1) dependency, got Depth=%d Direct=%v", requests.Depth, requests.Direct)
	}

	certifi := g.Nodes["certifi"]
	if certifi == nil {
		t.Fatalf("certifi node missing")
	}
	if certifi.Depth != 2 || certifi.Direct {
		t.Errorf("certifi should be transitive (depth 2, not direct), got Depth=%d Direct=%v", certifi.Depth, certifi.Direct)
	}

	pytest := g.Nodes["pytest"]
	if pytest == nil {
		t.Fatalf("pytest node missing")
	}
	if !pytest.Dev {
		t.Errorf("pytest (dev group) should have Dev=true")
	}
	if !pytest.Direct {
		t.Errorf("pytest is a direct dev dependency via pyproject.toml, should be Direct=true")
	}

	// urllib3 is an "optional" dependency of requests but IS present as its
	// own [[package]] entry (poetry resolved it), so the edge must be wired.
	urllib3 := g.Nodes["urllib3"]
	if urllib3 == nil {
		t.Fatalf("urllib3 node missing")
	}
	found := false
	for _, out := range requests.Out {
		if out == "urllib3" {
			found = true
		}
	}
	if !found {
		t.Errorf("requests.Out = %+v, expected an edge to urllib3", requests.Out)
	}
}

func TestParsePyProjectTOML_RejectsMissingPoetrySection(t *testing.T) {
	_, err := ParsePyProjectTOML([]byte(`[project]
name = "pep621-style"
dependencies = ["requests>=2.0"]
`))
	if err == nil {
		t.Fatalf("expected an error for PEP 621-native pyproject.toml (explicitly out of scope)")
	}
}
